//! Compares Sophia's view of a Julia package with Julia's own: for every
//! method Sophia stores, does Julia agree which generic function owns it?
//! And which of Julia's methods does Sophia not see at all? See
//! `julia_conformance.md` and [[Julia Conformance]].
//!
//! Usage:
//!   julia tests/julia-semantics/methods.jl PKG > truth.tsv
//!   cargo run --release -p sophia-ingest --example julia_conformance PKG_DIR truth.tsv [--by-name]
//!
//! Julia reports each method's source line and owner (`Module.name`;
//! constructors `Module.Type.new`). Sophia's side is the grouping rule
//! `sophia_ingest::binding` applied to the module-mode ingest. A method is
//! matched by (file, line of its first token). Constructor naming differs by
//! convention (Sophia writes `.new` only next to its own type), so `.new` is
//! ignored on both sides.

use std::collections::{BTreeMap, HashMap, HashSet};
use std::path::Path;

use sophia_ingest::{Binding, binding, module};

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let dir = Path::new(&args[1]);
    let truth = std::fs::read_to_string(&args[2]).unwrap();
    let (pkg, root) = module::package_root(dir).expect("Project.toml and src/<name>.jl");
    let src = dir.join("src");
    let by_name = args.iter().any(|a| a == "--by-name");

    // Julia: (file, line) → owners.
    let mut julia: HashMap<(String, usize), Vec<String>> = HashMap::new();
    for l in truth.lines() {
        let c: Vec<&str> = l.split('\t').collect();
        if c.len() == 3 {
            julia.entry((c[0].to_string(), c[1].parse().unwrap())).or_default().push(c[2].trim_end_matches(".new").to_string());
        }
    }

    // Sophia.
    let d = module::discover(&root).unwrap();
    let r = module::ingest(&d).unwrap();
    let mut seen: HashSet<(String, usize)> = HashSet::new();
    let mut tally: BTreeMap<&str, usize> = BTreeMap::new();
    let mut wrong: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut absent: Vec<String> = Vec::new();
    for (i, (path, items)) in r.files.iter().enumerate() {
        let rel = Path::new(path).strip_prefix(&src).unwrap_or(Path::new(path)).to_string_lossy().to_string();
        let text = &d.files[i].text;
        for (def, _) in items {
            let Some(Binding::Method(mut key)) = binding(def, &pkg) else { continue };
            // `--by-name`: the grouping before 2026-10-20, by bare name
            // under the package, for comparison.
            if by_name {
                key = vec![pkg.clone(), def.name.clone()];
            }
            let line = text[..def.start].matches('\n').count() + 1;
            let at = (rel.clone(), line);
            seen.insert(at.clone());
            let mine = key.join(".");
            match julia.get(&at) {
                None => {
                    *tally.entry("no Julia method at that line").or_default() += 1;
                    absent.push(format!("{rel}:{line} {mine}"));
                }
                Some(owners) if owners.contains(&mine) => *tally.entry("same owner").or_default() += 1,
                Some(owners) => {
                    *tally.entry("different owner").or_default() += 1;
                    let mut o = owners.clone();
                    o.sort();
                    o.dedup();
                    let class = format!("sophia {} / julia {}", pattern(&mine), o.iter().map(|x| pattern(x)).collect::<Vec<_>>().join(","));
                    wrong.entry(class).or_default().push(format!("{rel}:{line} {mine} ≠ {}", o.join(",")));
                }
            }
        }
    }
    let unseen: usize = julia.iter().filter(|(k, _)| !seen.contains(*k)).map(|(_, v)| v.len()).sum();
    let total: usize = julia.values().map(Vec::len).sum();
    println!("{pkg}: Sophia stores {} methods", tally.values().sum::<usize>());
    for (k, v) in &tally {
        println!("  {v:5}  {k}");
    }
    println!("Julia has {total} methods from these files; {unseen} at lines where Sophia stores no method (generated by @eval or macros, default constructors, refused definitions)");
    if !absent.is_empty() {
        println!("  no Julia method, e.g. {}", absent.iter().take(8).cloned().collect::<Vec<_>>().join("; "));
    }
    let mut classes: Vec<_> = wrong.into_iter().collect();
    classes.sort_by_key(|(_, v)| std::cmp::Reverse(v.len()));
    for (class, v) in classes {
        println!("  {:5}  {class}   e.g. {}", v.len(), v.iter().take(3).cloned().collect::<Vec<_>>().join("; "));
    }
}

/// `Base.Broadcast.copyto!` → `Base.Broadcast.*`, for grouping mismatches.
fn pattern(owner: &str) -> String {
    match owner.rsplit_once('.') {
        Some((m, _)) => format!("{m}.*"),
        None => owner.to_string(),
    }
}
